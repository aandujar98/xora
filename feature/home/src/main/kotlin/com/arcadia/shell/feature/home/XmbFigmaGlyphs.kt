/** Fills [glyph] centred in the current draw size, scaled to fit and mirrored when designed so. */
internal fun DrawScope.drawFigmaGlyph(glyph: FigmaGlyph, tint: Color) {
    val path = glyph.path
    val bounds = path.getBounds()
    if (bounds.width <= 0f || bounds.height <= 0f) return

    val scale = min(size.width / bounds.width, size.height / bounds.height)
    val drawn = Offset(bounds.width * scale, bounds.height * scale)
    withTransform({
        translate((size.width - drawn.x) / 2f, (size.height - drawn.y) / 2f)
        scale(scale, scale, pivot = Offset.Zero)
        if (glyph.mirrored) {
            scale(-1f, 1f, pivot = Offset(bounds.width / 2f, bounds.height / 2f))
        }
        translate(-bounds.left, -bounds.top)
    }) {
        drawPath(path, color = tint)
    }
}
